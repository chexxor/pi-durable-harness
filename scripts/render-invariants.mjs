// scripts/render-invariants.mjs - docs/world/reference/invariants.md is GENERATED from the structural rules
// this repo says it keeps, never kept beside them: a table of rules someone writes by hand reads true for a
// year and then reads true forever, the first time a rule stops being true and nothing notices. Run:
// node scripts/render-invariants.mjs > docs/world/reference/invariants.md
//
// PROVENANCE: no Durian-Pi original - Durian-Pi never printed the structural rules it claims beside the
// source tree that answers them, so this page is this repo's own. What it borrows is the page shape
// scripts/render-claims.mjs already uses for the claims index: the generator named at the top, one counted
// line, one row per item, and the words copied from the rows rather than paraphrased.
//
// WHY THE ROWS COME FROM scripts/invariants-check.mjs: this page and scripts/audit-invariants.mjs answer one
// question - does the source surface still keep these rules - this page as the table a reader opens, the gate
// as a hard exit. Two readers that each read the tree can disagree about a hit, and then the page says "kept"
// while the gate says "violated", with nothing to tell a reader which half is true. So the rows are built once
// in the file both of them import, and this generator adds prose around them and nothing else.
import { ruleRows, surface } from "./invariants-check.mjs";

const PAGE = "docs/world/reference/invariants.md";

/** What each rule keeps, in the words this repo already uses for it in README.md and the ADR. The rule's
 * counts come from the rows; only this description is written here, and it is keyed by the rule's id, so a
 * rule that gains or loses an id fails to render rather than printing a row nobody can match. */
const KEEPS = {
 storage_opener: "One storage opener, and it sits in the two files the rule names, so no run gains a store of its own.",
 mutation_line: "One mutation line, `writerSubmit` in `src/tui/writer.mjs`, so every committed turn walks the same write path.",
 ownership_sites: "The ownership claim, release and close, in `cli.mjs`' main try and finally, so a thrown run still releases the store.",
 raw_sql: "No SQL statement in the source and no sqlite module other than pi-durable's opener, so no write path exists outside the package.",
 pin_unmoved: "The pin stays at the tagged release, with no fallback standing in for a verdict about it.",
 dependencies_added: "The declared dependency set equals the pinned set, so the package set this repo proves has not grown.",
};

/** One row per rule: its own words, its own counts, the lines it answered at, and whether it is kept here. */
function ruleRow(row) {
 const kept = row.problems.length ? `VIOLATED (${row.problems.length} finding${row.problems.length === 1 ? "" : "s"})` : "kept";
 return `| ${row.id} | ${KEEPS[row.id] ?? "?"} | ${row.verdict} | ${row.lines.length} | ${kept} |`;
}

export function invariantLines() {
 const rows = ruleRows();
 const counts = surface();
 const kept = rows.filter((row) => !row.problems.length).length;
 const body = [];
 for (const row of rows) {
  body.push(`${row.id}: ${row.verdict}`);
  for (const line of row.lines) body.push(`  ${line}`);
 }
 return [
  "# Reference: the structural invariants this repo keeps at this tree",
  "",
  `Generated by \`scripts/render-invariants.mjs > ${PAGE}\` - one row per rule, the counts copied from the same`,
  "rows `scripts/audit-invariants.mjs` fails on. Regenerate it with that redirect and never hand-edit it:",
  "an edited copy cannot be told from a page that went stale, and every number on this page comes from a run.",
  "",
  "These are the binding rules [the ADR](../decisions/0001-docs-kinds-and-style.md) states and README.md's",
  "\"Before you change anything\" names: one storage opener, one mutation line, the ownership claim released",
  "in `cli.mjs`' main finally, no raw SQL, the pin unmoved, no dependency added. The demos prove behaviour a",
  "caller can see; none of them proves the SHAPE of the code, and an extra opener in a file no demo imports",
  "passes all of them. So the shape is read off the tracked source once, in `scripts/invariants-check.mjs`,",
  "and both readers import those rows: the gate as a hard exit, this page as the table.",
  "",
  `source surface read=${counts.read} tracked .mjs (cli.mjs + src/, ${counts.data.join(", ")} held out as DATA`,
  `prose about these rules rather than code that could break one); not read=${counts.exempt} .mjs (demo/ fixtures`,
  "measure the rules against their own stores, and scripts/ auditors read the rules in order to check them)",
  "",
  `invariants checked=${rows.length} kept=${kept} violated=${rows.length - kept}`,
  "",
  "The tree this table answers for is the tree this page sits on, and `git rev-parse HEAD` reads it; the gate",
  "prints the same counts beside the tree its own verdict names, so the two can be compared for one run.",
  "",
  "| rule | what it keeps | counted at this tree | sites | kept here |",
  "| --- | --- | --- | --- | --- |",
  ...rows.map(ruleRow),
  "",
  "The `sites` column counts the code lines each rule answered at, so a rule that keeps says where it keeps,",
  "not just that it keeps. A violated rule prints its findings instead, indented, naming file and line, and",
  "`scripts/audit-invariants.mjs` exits 1 on the same rows this table prints.",
  "",
  "The same rows, printed the way the gate prints them:",
  "",
  "```text",
  ...body,
  "```",
  "",
  "What falsifies this page: plant a second opener in a file the rules read, define a second mutation line,",
  "move the release out of `cli.mjs`' finally block, write an SQL statement into a source file, move the pin,",
  "or declare a dependency the pin does not carry - each one turns exactly one row red and fails the gate",
  "with the file and line named. The rules are checked rather than believed because a paragraph cannot be",
  "planted against; this table can.",
  "",
  "Related: [the runbook](../runbooks/next-milestone.md) states what a milestone must keep when it changes",
  "code, [verify a claim offline](../how-to/verify-a-claim-offline.md) walks the gates that read this tree,",
  "and [the claims index](claims-index.md) lists the findings this repo carries against the same tree.",
 ];
}

if (import.meta.main) {
 for (const line of invariantLines()) console.log(line);
}
