// scripts/audit-provenance.mjs - every source file in this repo must carry a provenance header, and the
// claim "every extracted file carries one" has to be checked rather than asserted.
//
// PROVENANCE: no Durian-Pi original - this checks the rule the user's own extraction policy states (every
// extracted file names the file it came from, and what changed), which is a claim this repo makes about
// itself; the check exists so that claim can be falsified after the fact rather than remembered.
//
// WHY A CHECK AND NOT A LIST: a hand-written list of the files that carry headers goes stale the first
// time a file is added or edited - and stale here means a policy violation nobody sees. This script reads
// the header it requires, reports the file it could not find one in, and prints the header text it found,
// so the docs generated from it are a copy of the source's own words rather than a paraphrase of them.
//
// What counts as a header, in this repo's own words: within the first 40 lines, a comment line that starts
// `PROVENANCE` or `Source:` - either naming the Durian-Pi file it was extracted from, or saying out loud
// that there is no Durian-Pi original, which is a different claim and must not be left blank.
import { readdirSync, readFileSync } from "node:fs";
import { join } from "node:path";

// What is NOT this repo's source: pi's own installed packages (whose headers are pi's policy, not ours),
// the scratch tree of probes, and the state directories pi extensions keep next to the project.
function sourceFiles(dirs) {
 const out = [];
 for (const dir of dirs) {
 let names = [];
 try {
 names = readdirSync(dir, { recursive: true, encoding: "utf8" });
 } catch {
 continue;
 }
 for (const name of names) {
 if (!String(name).endsWith(".mjs")) continue;
 const path = join(dir, name);
 if (path.includes("node_modules") || path.startsWith(".scratch") || path.startsWith(".tmp") || path.startsWith(".pi/") || path.startsWith(".ai-work/") || path.startsWith("vendor/")) continue;
 out.push(path);
 }
 }
 return out;
}

const files = sourceFiles(["src", "demo", "scripts", "."]).filter((path) => path !== join("scripts", "audit-provenance.mjs"));
const missing = [];
const headers = [];
for (const path of files) {
 const lines = readFileSync(path, "utf8").split("\n").slice(0, 40);
 let provenance = "";
 for (const line of lines) {
 const trimmed = line.replace(/^\s*(\/\/+|\/\*|\*)\s?/, "").trim();
 if (/^(provenance\b|source:)/i.test(trimmed)) {
 provenance = trimmed;
 break;
 }
 }
 if (!provenance) {
 missing.push(path);
 continue;
 }
 const verified = lines.some((line) => /VERIFIED AGAINST PINED/i.test(line));
 const dropped = lines.some((line) => /dropped|not reimplemented|omitted|what changed/i.test(line));
 headers.push({ path, provenance, verified, dropped });
}

console.log(`headers found in ${headers.length}/${files.length} source files`);
for (const path of missing) console.log(` MISSING HEADER: ${path}`);
if (process.argv[2] === "--markdown") {
 console.log("");
 console.log("Generated by `scripts/audit-provenance.mjs --markdown` - the header text is each file's own words, copied, not paraphrased.");
 console.log("");
 console.log("| file | provenance line | names pinned symbols it was read against | says what was dropped |");
 console.log("| --- | --- | --- | --- |");
 for (const entry of headers) {
 console.log(`| ${entry.path} | ${entry.provenance.replace(/^\|/, "\\|").slice(0, 300)} | ${entry.verified ? "yes" : "-"} | ${entry.dropped ? "yes" : "-"} |`);
 }
}
if (missing.length) {
 console.log(`PROVENANCE FAIL: ${missing.length} files without a provenance header`);
 process.exit(1);
}
console.log("PROVENANCE PASS: every source file names the source it was extracted from, or says there is none");
