// scripts/render-matrix.mjs - docs/package-support.md is GENERATED from src/packages/matrix.mjs, never
// kept beside it: two places that name the same capability drift silently the first time one of them is
// edited, and a reader cannot tell which half is true. Run:
// node scripts/render-matrix.mjs > docs/package-support.md
import { capabilityMatrix, renderMatrixMarkdown, unmappedRuntime } from "../src/packages/matrix.mjs";
import { packageRoots, discoverPackages, extensionPaths } from "../src/packages/discover.mjs";
import { loadPiExtensions } from "../src/packages/loader.mjs";
import { adaptPiExtension } from "../src/packages/adapter.mjs";
import { getAgentDir } from "@earendil-works/pi-coding-agent";
import { existsSync } from "node:fs";
import { join } from "node:path";

/**
 * The runtime half of the doc: the pi packages that are ACTUALLY on this machine, what loaded from them,
 * and what did not map.
 *
 * This is generated by running the loader rather than being written, because the alternative - a list of
 * package names someone remembered - turns a package that stops installing, or one that gains a capability,
 * into a doc that is quietly wrong. `unmappedRuntime()` is asserted here too: a non-empty result means the
 * matrix does not name a capability that this machine's extensions register, which is a hard failure for
 * the render rather than a note, since the doc's whole claim is that nothing unmapped goes unnamed.
 */
async function runtimePlane() {
 const agentDir = getAgentDir();
 const discovered = discoverPackages(packageRoots(process.cwd(), agentDir));
 const loaded = await loadPiExtensions(extensionPaths(discovered), process.cwd(), agentDir);
 const inventory = [];
 for (const extension of loaded.extensions) adaptPiExtension(extension, { name: `pi:${extension.path}`, inventory });
 const unmapped = unmappedRuntime(inventory);
 if (unmapped.length) {
 console.error(`matrix does not name: ${unmapped.map((row) => `${row.capability} ${row.name}`).join(", ")}`);
 process.exit(1);
 }
 return {
 packages: discovered.found.map((row) => `| ${row.package} @ ${row.version} | ${row.plane} | ${Object.entries(row.resolved).map(( [kind, entries]) => `${kind} x${entries.length}`).join(", ") || "none"} | ${loaded.extensions.filter((e) => e.path.includes(row.root)).length} | ${loaded.errors.filter((e) => e.path.includes(row.root)).length} |`),
 loaderErrors: loaded.errors.map((row) => `| ${row.path} | ${row.error} |`),
 declaredMissing: discovered.missing.map((row) => `| ${row.package} | ${row.kind} | ${row.path} | ${row.reason} |`),
 };
}

const runtime = await runtimePlane();
const counts = Object.fromEntries(["native", "shimmed", "unsupported"].map((status) => [status, capabilityMatrix(status).length]));

console.log(
"# pi package support matrix\n" +
"\n" +
"One row per pi capability, and nothing here is a guess: the rows live as data in\n" +
"`src/packages/matrix.mjs`, and this file is what `scripts/render-matrix.mjs` renders from that data. Edit\n" +
"the data, not this file - a doc edited beside the data cannot be checked against it, and the whole point\n" +
"of the matrix is that an unsupported capability is NAMED, so an un-named capability is a finding rather\n" +
"than a shrug.\n" +
"\n" +
"Status meanings, since the three words carry the contract:\n" +
"\n" +
"- `native` - pi-durable has the concept and the harness uses pi-durable's own; no shim is involved.\n" +
"- `shimmed` - pi's shape is translated onto pi-durable's by `src/packages/adapter.mjs`, and the named\n" +
" demo exercises the result.\n" +
"- `unsupported` - no pi-durable counterpart exists at the pinned release; the `why` column says what\n" +
" pi-durable lacks, which is what makes the row falsifiable if a later release gains the concept.\n" +
"\n" +
"## The matrix\n\n" +
renderMatrixMarkdown(null, existsSync) +
"\n\n" +
`Rows: ${counts.native} native, ${counts.shimmed} shimmed, ${counts.unsupported} unsupported.\n` +
"\n" +
"## What is actually installed on THIS machine, and what loaded from it\n" +
"\n" +
"Generated by the same script that renders the matrix, from `src/packages/discover.mjs` reading both of\n" +
"pi's package planes and `src/packages/loader.mjs` handing the found paths to pi's own loader. A row here\n" +
"that shows `0` loaded extensions is a package that is installed but whose extension modules did not\n" +
"load, and the loader errors below say why.\n\n" +
"| package | plane | manifest kinds | loaded | loader errors |\n" +
"| --- | --- | --- | --- | --- |\n" +
runtime.packages.join("\n") +
"\n\n" +
"### Loader failures, named rather than swallowed\n\n" +
"| path | error |\n| --- | --- |\n" +
(runtime.loaderErrors.length ? runtime.loaderErrors.join("\n") : "_none: every extension module that discovery found loaded_") +
"\n\n" +
"### Declared by a manifest and not on disk, or a kind no layer implements\n\n" +
"| package | kind | path | why |\n| --- | --- | --- | --- |\n" +
(runtime.declaredMissing.length ? runtime.declaredMissing.join("\n") : "_none_") +
"\n\n" +
"## How to read an `unsupported` row\n" +
"\n" +
"An `unsupported` row is not a to-do list. It names what pi-durable does not have at this pin, and the\n" +
"harness's answer to such a capability is to load the package, keep the registrations it can use, and\n" +
"report the rest - because a loader that quietly ignored what it cannot map would make a capability claim\n" +
"impossible to audit. Where a capability is pi's UI plane (commands, shortcuts, renderers, TUI hooks), the\n" +
"harness's own TUI and CLI own that surface instead: the pi package still loads, and its tools, handlers,\n" +
"skills, prompts, themes and context files still reach the model, while a pi renderer has nothing to\n" +
"attach to.\n" +
"\n" +
"## The package plane, and what is not\n" +
"\n" +
"Discovery and loading are this harness's, through pi's own library exports: the packages found on disk are\n" +
"loaded by pi's loader (jiti, against pi's own `ExtensionRuntime`). What is NOT done is installing a package\n" +
"that is not on disk: `DefaultPackageManager` resolves from npm and git over the network, and every demo in\n" +
"this repo runs offline. A package that is configured and not installed is reported as absent by discovery -\n" +
"the honest half - and installing it stays the `pi` CLI's job.\n"
);
