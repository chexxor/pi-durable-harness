// scripts/render-claims.mjs - docs/world/reference/claims-index.md is GENERATED from the claim pages, never
// kept beside them: an index of findings that someone writes by hand goes stale the first time a claim is
// fixed, reworded, added, or dropped, and nothing notices. Run:
// node scripts/render-claims.mjs > docs/world/reference/claims-index.md
//
// PROVENANCE: no Durian-Pi original - Durian-Pi never indexed findings against a tree, so this index is this
// repo's own page. What it borrows is the row shape scripts/render-matrix.mjs already uses for the capability
// matrix: one row per item, the item's own words copied rather than paraphrased, and the generator named at
// the top of the page.
//
// WHY THE ROWS COME FROM scripts/claims-check.mjs: the index and scripts/audit-claim-drift.mjs describe the
// same blocks, one for the next milestone and one as a hard failure. If this file read the markdown itself,
// the two could disagree about a block and a reader would have no way to tell which half was true.
import { claimRows } from "./claims-check.mjs";

const PAGE = "docs/world/reference/claims-index.md";

/** One row per claim: the page's own claim sentence, the tree and pin it cites, and whether it still answers here. */
function indexRow(item) {
 const cells = [
  item.area || "?",
  String(item.claim || "").replace(/\|/g, "\\|"),
  `[${item.id}](../claims/${item.id}.md)`,
  item.state,
  item.tree.slice(0, 12) || "?",
  item.pin.slice(0, 12) || "?",
  item.status === "current" ? "answers as quoted" : `STALE (${item.problems.length} finding${item.problems.length === 1 ? "" : "s"})`,
 ];
 return `| ${cells.join(" | ")} |`;
}

export function indexLines() {
 const rows = claimRows();
 const areas = {};
 const states = {};
 let current = 0;
 for (const row of rows) {
  areas[row.area || "?"] = (areas[row.area || "?"] ?? 0) + 1;
  states[row.state] = (states[row.state] ?? 0) + 1;
  if (row.status === "current") current += 1;
 }
 const counted = (obj) => Object.entries(obj).map(([key, value]) => `${key}=${value}`).sort().join(" ");
 return [
  "# Reference: the claims index at this tree",
  "",
  `Generated by \`scripts/render-claims.mjs > ${PAGE}\` - one row per page under docs/world/claims/, the claim`,
  "sentence copied from the page rather than paraphrased, and the tree and pin the page cites. The column",
  "that matters is the last one: `answers as quoted` means the page's command still answers on the tree this",
  "repo sits on, and `STALE` means it stopped answering, which is what `scripts/audit-claim-drift.mjs` fails",
  "on. Read the numbers from the run below them, never from memory.",
  "",
  `claims checked=${rows.length} current=${current} stale=${rows.length - current} areas=${counted(areas)} states=${counted(states)}`,
  "",
  "| area | claim | page | state | tree cited | pin cited | status at HEAD |",
  "| --- | --- | --- | --- | --- | --- | --- |",
  ...rows.map(indexRow),
  "",
  "The findings themselves are in each row's page; the gate prints the reasons a row is stale. Nothing here",
  "fixes a claim: the next milestone reads this page and picks one row.",
  "",
  "Related: the [runbook](../runbooks/next-milestone.md) states what the next milestone does with a row, and",
  "the [provenance table](provenance.md) names where each source file came from.",
 ];
}

if (import.meta.main) {
 for (const line of indexLines()) console.log(line);
}
